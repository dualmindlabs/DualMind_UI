// Writes docs/api/openapi.v2.json and docs/api/problems.md from the v2 routes (BE-0 design,
// section 6.5). `--check` writes nothing and exits 1 when a committed file is out of date.
//   node scripts/generate-openapi.ts           (Node 22.18+ strips the types)
//   node scripts/generate-openapi.ts --check
// Needs the Worker dependencies: node scripts/link-worker-deps.mjs links web/node_modules.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PROBLEM_TYPES, problemTypeUrl } from '../server/problem-types.js';
import { createApp, openapiConfig } from '../server/v2/app.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
const openapiPath = `${root}docs/api/openapi.v2.json`;
const problemsPath = `${root}docs/api/problems.md`;

function renderProblems(): string {
  const rows = Object.entries(PROBLEM_TYPES).map(
    ([slug, entry]) => `| \`${slug}\` | ${entry.status} | ${entry.title} | ${entry.usedFor} |`,
  );
  return [
    '# Problem types',
    '',
    '<!-- Generated by scripts/generate-openapi.ts from server/problem-types.js. Do not edit; run `npm run api:openapi`. -->',
    '',
    'Every error under `/api/v2` is `application/problem+json` ([RFC 9457](https://www.rfc-editor.org/rfc/rfc9457)). The `type` is the identifier URL below; clients must not depend on it resolving.',
    '',
    '| Slug | Status | Title | Used for |',
    '| --- | ---: | --- | --- |',
    ...rows,
    '',
    `Identifier URL: \`${problemTypeUrl('<slug>')}\`.`,
    '',
  ].join('\n');
}

const outputs: [string, string][] = [
  [openapiPath, `${JSON.stringify(createApp().getOpenAPI31Document(openapiConfig), null, 2)}\n`],
  [problemsPath, renderProblems()],
];

const check = process.argv.includes('--check');
let stale = false;
for (const [path, content] of outputs) {
  if (check) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // missing counts as stale
    }
    if (current !== content) {
      console.error(`${path.replace(root, '')} is out of date. Run \`npm run api:openapi\` and commit the result.`);
      stale = true;
    }
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${path.replace(root, '')}`);
  }
}
process.exit(stale ? 1 : 0);
